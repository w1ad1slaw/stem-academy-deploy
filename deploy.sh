#!/bin/bash
# ============================================================
# Скрипт автоматического развертывания среды «STEM Академия»
# (установка ПО, настройка прав доступа, создание структуры проектов)
# ============================================================

# Цвета для вывода (улучшают читаемость)
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # Без цвета

# Функция вывода заголовка этапа
print_header() {
    echo -e "\n${YELLOW}=== $1 ===${NC}\n"
}

# Функция вывода успешного завершения
print_success() {
    echo -e "${GREEN}[✓] $1${NC}"
}

# Функция вывода ошибки
print_error() {
    echo -e "${RED}[✗] $1${NC}"
}

# -----------------------------------------------------------
# ПРОВЕРКА ПРАВ СУПЕРПОЛЬЗОВАТЕЛЯ
# Скрипт требует прав root для установки пакетов и изменения
# системных настроек (группы пользователей, права на порты)
# -----------------------------------------------------------
if [ "$EUID" -ne 0 ]; then
    print_error "Скрипт должен быть запущен от имени суперпользователя"
    echo "Используйте: sudo ./deploy.sh"
    exit 1
fi

print_header "Начало развертывания среды STEM Академия"

# -----------------------------------------------------------
# ЭТАП 1: ОБНОВЛЕНИЕ СИСТЕМЫ
# Обновление списков пакетов и установка доступных обновлений
# -----------------------------------------------------------
print_header "Этап 1: Обновление системы"

echo "Обновление списков пакетов..."
apt update -y

echo "Установка доступных обновлений..."
apt upgrade -y

print_success "Система обновлена"

# -----------------------------------------------------------
# ЭТАП 2: УСТАНОВКА НЕОБХОДИМОГО ПРОГРАММНОГО ОБЕСПЕЧЕНИЯ
# python3 и pip3 - для скриптов взаимодействия с микроконтроллерами
# git - для работы с репозиториями кода
# python3-serial - библиотека pyserial для работы с последовательными портами
# minicom - терминальная программа для отладки UART-соединений
# arduino-cli - инструмент командной строки для работы с Arduino
# -----------------------------------------------------------
print_header "Этап 2: Установка программного обеспечения"

PACKAGES="python3 python3-pip git python3-serial minicom arduino-cli"

echo "Установка пакетов: $PACKAGES"
apt install -y $PACKAGES

# Проверка успешности установки
if [ $? -eq 0 ]; then
    print_success "Все пакеты успешно установлены"
else
    print_error "Ошибка при установке пакетов"
    exit 1
fi

# -----------------------------------------------------------
# ЭТАП 3: НАСТРОЙКА ПРАВ ДОСТУПА К ОБОРУДОВАНИЮ
# Добавление текущего пользователя в группу 'dialout'
# необходимо для получения прав на чтение/запись в последовательные
# порты (/dev/ttyUSB0, /dev/ttyACM0) без использования sudo
# -----------------------------------------------------------
print_header "Этап 3: Настройка прав доступа к оборудованию"

# Получение имени текущего пользователя (не root, а того, кто вызвал sudo)
CURRENT_USER=${SUDO_USER:-$(logname)}

echo "Добавление пользователя $CURRENT_USER в группу dialout..."
usermod -a -G dialout $CURRENT_USER

if [ $? -eq 0 ]; then
    print_success "Пользователь $CURRENT_USER добавлен в группу dialout"
else
    print_error "Ошибка при добавлении пользователя в группу"
    exit 1
fi

# -----------------------------------------------------------
# ЭТАП 4: СОЗДАНИЕ РАБОЧЕЙ СТРУКТУРЫ ПРОЕКТОВ
# Создание директории для проектов STEM Academy в домашнем каталоге
# -----------------------------------------------------------
print_header "Этап 4: Создание рабочей структуры"

PROJECT_DIR="/home/$CURRENT_USER/STEM_Academy_Projects"

if [ ! -d "$PROJECT_DIR" ]; then
    echo "Создание директории: $PROJECT_DIR"
    mkdir -p "$PROJECT_DIR"
    chown $CURRENT_USER:$CURRENT_USER "$PROJECT_DIR"
    print_success "Рабочая директория создана"
else
    print_success "Рабочая директория уже существует"
fi

# Создание поддиректорий для организации проектов
mkdir -p "$PROJECT_DIR/Arduino_Sketches"
mkdir -p "$PROJECT_DIR/Python_Scripts"
mkdir -p "$PROJECT_DIR/Documentation"

chown -R $CURRENT_USER:$CURRENT_USER "$PROJECT_DIR"

print_success "Структура проектов создана"

# -----------------------------------------------------------
# ЭТАП 5: ПРОВЕРКА УСТАНОВЛЕННЫХ КОМПОНЕНТОВ
# Вывод версий установленного ПО для отчёта
# -----------------------------------------------------------
print_header "Этап 5: Проверка установленных компонентов"

echo "Версия Python: $(python3 --version)"
echo "Версия pip: $(pip3 --version)"
echo "Версия Git: $(git --version)"
echo "Версия Arduino CLI: $(arduino-cli version)"

# -----------------------------------------------------------
# ЗАВЕРШЕНИЕ
# -----------------------------------------------------------
print_header "Развертывание завершено"